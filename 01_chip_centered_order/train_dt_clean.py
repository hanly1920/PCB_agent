# Utility: Hard constraints check (boundary, overlap, spacing)
# --------------------
def satisfies_hard_constraints(processor, placement_sequence: List[Dict[str, Any]], grid_size: int, margin: int) -> bool:
    """
    Basic legality check:
    - components must be within boundary (0..grid_size)
    - no overlap between placed components (consider rotated size)
    - spacing >= rule-derived requirement (grid units)
    placement_sequence: list of dict with keys: comp_id, x, y, rot, w, h
    """
    # boundary check
    for comp in placement_sequence:
        w, h = comp['w'], comp['h']
        rot = comp['rot']
        if rot % 2 == 1:
            w, h = h, w
        x, y = comp['x'], comp['y']
        if x < 0 or y < 0 or x + w > grid_size or y + h > grid_size:
            return False

    # overlap + spacing check (AABB with margin)
    def aabb(x, y, w, h):
        return (x, y, x + w, y + h)

    def expanded(box, m):
        x1, y1, x2, y2 = box
        return (x1 - m, y1 - m, x2 + m, y2 + m)

    boxes = []
    comp_type_lookup = {}
    if hasattr(processor, "component_list"):
        for comp in processor.component_list:
            comp_type_lookup[comp["comp_id"]] = comp.get("type_id", 0)

    body_rules = getattr(processor, "body_spacing_rules", {}) or {}

    def spacing_requirement(comp_id_a: int, comp_id_b: int) -> int:
        type_a = comp_type_lookup.get(comp_id_a)
        type_b = comp_type_lookup.get(comp_id_b)
        if type_a is not None and type_b is not None:
            if (type_a, type_b) in body_rules:
                return int(body_rules[(type_a, type_b)])
            if (type_b, type_a) in body_rules:
                return int(body_rules[(type_b, type_a)])
        return margin

    for comp in placement_sequence:
        w, h = comp['w'], comp['h']
        rot = comp['rot']
        if rot % 2 == 1:
            w, h = h, w
        boxes.append((comp['comp_id'], aabb(comp['x'], comp['y'], w, h)))

    for i in range(len(boxes)):
        for j in range(i + 1, len(boxes)):
            comp_id_i, bi = boxes[i]
            comp_id_j, bj = boxes[j]
            # overlap check
            if not (bi[2] <= bj[0] or bj[2] <= bi[0] or bi[3] <= bj[1] or bj[3] <= bi[1]):
                return False
            requirement = spacing_requirement(comp_id_i, comp_id_j)
            if requirement <= 0:
                continue

            ei = expanded(bi, requirement)
            ej = expanded(bj, requirement)
            if not (ei[2] <= ej[0] or ej[2] <= ei[0] or ei[3] <= ej[1] or ej[3] <= ei[1]):
                dx = 0.0
                if bi[2] < bj[0]:
                    dx = bj[0] - bi[2]
                elif bj[2] < bi[0]:
                    dx = bi[0] - bj[2]

                dy = 0.0
                if bi[3] < bj[1]:
                    dy = bj[1] - bi[3]
                elif bj[3] < bi[1]:
                    dy = bi[1] - bj[3]

                if dx == 0.0 and dy == 0.0:
                    distance = 0.0
                elif dx == 0.0:
                    distance = dy
                elif dy == 0.0:
                    distance = dx
                else:
                    distance = math.hypot(dx, dy)

                if distance < requirement:
                    return False
    return True

