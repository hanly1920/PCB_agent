"""Decision Transformer RL-style online fine-tuning on clean trajectories (paper-aligned).

This version moves from pure supervised training to an RL-style loop closer to the paper:
- Generate trajectories with current policy (Algorithm 1 style)
- Keep only those satisfying hard constraints (boundary, overlap, spacing)
- Compute score = λ1·1/HPWL + λ2·NSLW
- Prioritized replay: sample by ω(τ) = exp(score/α) / E_B[exp(score/α)]
- Update policy via L(θ) = − E_B[ ω(τ) · log π_θ(a_t | τ_t) ]

Notes:
- We reuse ExpertTrajectoryDataset to provide task info and helpers, but actions fed to the
    model are generated by the current policy, not supervised labels.
- Returns-to-go are computed from rewards r_t = HPWL_{t-1} − HPWL_{t-2} within the rollout.
"""
